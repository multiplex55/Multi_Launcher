//! Independent, exact integer inspector state. This module performs no Pad edits.
use super::{DocumentId, IntegerError, IntegerMode, IntegerWidth, LineId, TypedInteger};
use crate::common::numeric_base::{NumericBase, format_unsigned};
use std::ops::Range;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct DocumentIncarnation(pub(super) DocumentId);

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InspectorSourceOrigin {
    TypedInteger,
    LegacyExactBase,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InspectorSourceSnapshot {
    pub incarnation: DocumentIncarnation,
    pub document_id: DocumentId,
    pub revision: u64,
    pub line_id: LineId,
    pub source_range: Range<usize>,
    pub source_text: std::sync::Arc<str>,
    pub value: TypedInteger,
    pub origin: InspectorSourceOrigin,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InspectorAnnotation {
    pub range: Range<u32>,
    pub label: String,
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct InspectorFormatOptions {
    pub prefix: bool,
    pub pad_to_width: bool,
    /// Digits per group; zero disables grouping.
    pub grouping: u8,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum InspectorError {
    NoCandidate,
    NoAdoptedSource,
    InvalidBitIndex { index: u32, width: u32 },
    InvalidRange,
    TooManyAnnotations,
    LabelTooLong,
    InvalidGrouping,
    Integer(IntegerError),
}
impl From<IntegerError> for InspectorError {
    fn from(value: IntegerError) -> Self {
        Self::Integer(value)
    }
}

/// An immutable source binding and replacement generated by the inspector.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InspectorInsertRequest {
    pub(super) source: InspectorSourceSnapshot,
    pub(super) target: Range<usize>,
    pub(super) expression: String,
}
impl InspectorInsertRequest {
    pub fn source(&self) -> &InspectorSourceSnapshot {
        &self.source
    }
    pub fn target(&self) -> &Range<usize> {
        &self.target
    }
    pub fn expression(&self) -> &str {
        &self.expression
    }
}

#[derive(Clone, Debug)]
pub struct ProgrammerInspector {
    adopted: Option<InspectorSourceSnapshot>,
    candidate: Option<InspectorSourceSnapshot>,
    working: TypedInteger,
    baseline: TypedInteger,
    annotations: Vec<InspectorAnnotation>,
    baseline_annotations: Vec<InspectorAnnotation>,
    format: InspectorFormatOptions,
}
impl Default for ProgrammerInspector {
    fn default() -> Self {
        let value = TypedInteger::zero(IntegerMode::unsigned(IntegerWidth::Bits64));
        Self {
            adopted: None,
            candidate: None,
            working: value,
            baseline: value,
            annotations: Vec::new(),
            baseline_annotations: Vec::new(),
            format: InspectorFormatOptions::default(),
        }
    }
}
impl ProgrammerInspector {
    pub fn adopted(&self) -> Option<&InspectorSourceSnapshot> {
        self.adopted.as_ref()
    }
    pub fn candidate(&self) -> Option<&InspectorSourceSnapshot> {
        self.candidate.as_ref()
    }
    pub fn value(&self) -> TypedInteger {
        self.working
    }
    pub fn set_value(&mut self, value: TypedInteger) {
        self.working = value;
    }
    pub fn numeric_dirty(&self) -> bool {
        self.working != self.baseline
    }
    pub fn has_local_work(&self) -> bool {
        self.numeric_dirty() || self.annotations != self.baseline_annotations
    }
    pub fn annotations(&self) -> &[InspectorAnnotation] {
        &self.annotations
    }
    pub fn format_options(&self) -> InspectorFormatOptions {
        self.format
    }
    pub fn set_format_options(
        &mut self,
        options: InspectorFormatOptions,
    ) -> Result<(), InspectorError> {
        if options.grouping > 128 {
            return Err(InspectorError::InvalidGrouping);
        }
        self.format = options;
        Ok(())
    }
    /// Observe without changing the Pad; dirty local work always keeps its binding.
    pub fn observe(&mut self, candidate: Option<InspectorSourceSnapshot>) {
        self.candidate = candidate;
        if !self.has_local_work() && self.candidate.is_some() {
            let _ = self.refresh();
        }
    }
    pub fn refresh(&mut self) -> Result<(), InspectorError> {
        let source = self.candidate.clone().ok_or(InspectorError::NoCandidate)?;
        self.working = source.value;
        self.baseline = source.value;
        self.adopted = Some(source);
        self.baseline_annotations = self.annotations.clone();
        Ok(())
    }
    fn validate_index(&self, index: u32) -> Result<(), InspectorError> {
        let width = self.working.mode().width().bits();
        if index >= width {
            Err(InspectorError::InvalidBitIndex { index, width })
        } else {
            Ok(())
        }
    }
    pub fn bit(&self, index: u32) -> Result<bool, InspectorError> {
        self.validate_index(index)?;
        Ok(self.working.bit_pattern() & (1_u128 << index) != 0)
    }
    pub fn toggle_bit(&mut self, index: u32) -> Result<(), InspectorError> {
        self.validate_index(index)?;
        self.working = TypedInteger::from_bit_pattern(
            self.working.bit_pattern() ^ (1_u128 << index),
            self.working.mode(),
        )?;
        Ok(())
    }
    pub fn bit_not(&mut self) {
        self.working = self.working.bit_not();
    }
    pub fn popcount(&self) -> u32 {
        self.working.popcount()
    }
    pub fn shift_left(&mut self, count: i128) -> Result<(), InspectorError> {
        self.working = self.working.shift_left(count)?;
        Ok(())
    }
    pub fn shift_right(&mut self, count: i128) -> Result<(), InspectorError> {
        self.working = self.working.shift_right(count)?;
        Ok(())
    }
    pub fn rotate_left(&mut self, count: i128) -> Result<(), InspectorError> {
        self.working = self.working.rotate_left(count)?;
        Ok(())
    }
    pub fn rotate_right(&mut self, count: i128) -> Result<(), InspectorError> {
        self.working = self.working.rotate_right(count)?;
        Ok(())
    }
    pub fn field_mask(&mut self, start: u32, count: u32) -> Result<(), InspectorError> {
        self.working = self.working.field_mask(start, count)?;
        Ok(())
    }
    pub fn extract_bits(&mut self, start: u32, count: u32) -> Result<(), InspectorError> {
        self.working = self.working.extract_bits(start, count)?;
        Ok(())
    }
    pub fn checked_cast(&mut self, mode: IntegerMode) -> Result<(), InspectorError> {
        self.working = self.working.checked_cast(mode)?;
        Ok(())
    }
    pub fn reinterpret_bits(&mut self, mode: IntegerMode) {
        self.working = self.working.reinterpret_bits(mode);
    }
    pub fn set_annotation(
        &mut self,
        range: Range<u32>,
        label: String,
    ) -> Result<(), InspectorError> {
        if range.start >= range.end || range.end > self.working.mode().width().bits() {
            return Err(InspectorError::InvalidRange);
        }
        if label.len() > 128 {
            return Err(InspectorError::LabelTooLong);
        }
        if let Some(existing) = self
            .annotations
            .iter_mut()
            .find(|entry| entry.range == range)
        {
            existing.label = label;
        } else {
            if self.annotations.len() >= 128 {
                return Err(InspectorError::TooManyAnnotations);
            }
            self.annotations.push(InspectorAnnotation { range, label });
        }
        Ok(())
    }
    pub fn remove_annotation(&mut self, range: Range<u32>) {
        self.annotations.retain(|entry| entry.range != range);
    }
    pub fn annotation_is_valid(&self, annotation: &InspectorAnnotation) -> bool {
        annotation.range.start < annotation.range.end
            && annotation.range.end <= self.working.mode().width().bits()
    }
    pub fn format(&self, base: NumericBase) -> String {
        let width = self.working.mode().width();
        let decimal = base == NumericBase::Decimal;
        let value = if decimal {
            self.working.formatted_decimal()
        } else {
            format_unsigned(self.working.bit_pattern(), base)
        };
        let (sign, digits) = value
            .strip_prefix('-')
            .map_or(("", value.as_str()), |s| ("-", s));
        let size = if !self.format.pad_to_width {
            0
        } else {
            match base {
                NumericBase::Binary => width.bits() as usize,
                NumericBase::Octal => width.bits().div_ceil(3) as usize,
                NumericBase::Hexadecimal => width.bits().div_ceil(4) as usize,
                NumericBase::Decimal => format_unsigned(width.bit_mask(), base).len(),
            }
        };
        let padded = format!("{:0>width$}", digits, width = size);
        let group = self.format.grouping as usize;
        let mut grouped = String::with_capacity(padded.len() * 2);
        for (index, ch) in padded.chars().enumerate() {
            if group > 0 && index > 0 && (padded.len() - index) % group == 0 {
                grouped.push('_');
            }
            grouped.push(ch);
        }
        let prefix = if self.format.prefix {
            match base {
                NumericBase::Binary => "0b",
                NumericBase::Octal => "0o",
                NumericBase::Hexadecimal => "0x",
                NumericBase::Decimal => "",
            }
        } else {
            ""
        };
        format!("{sign}{prefix}{grouped}")
    }
    pub fn canonical_expression(&self) -> String {
        format!(
            "{}({})",
            self.working.mode().type_name(),
            self.working.formatted_decimal()
        )
    }
    pub fn insert_request(
        &self,
        target: Range<usize>,
    ) -> Result<InspectorInsertRequest, InspectorError> {
        Ok(InspectorInsertRequest {
            source: self
                .adopted
                .clone()
                .ok_or(InspectorError::NoAdoptedSource)?,
            target,
            expression: self.canonical_expression(),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn inspector_bits_labels_and_formats_stay_exact() {
        let mut inspector = ProgrammerInspector::default();
        inspector.reinterpret_bits(IntegerMode::signed(IntegerWidth::Bits8));
        inspector.toggle_bit(0).unwrap();
        inspector.toggle_bit(7).unwrap();
        assert!(inspector.bit(0).unwrap() && inspector.bit(7).unwrap());
        assert!(matches!(
            inspector.bit(8),
            Err(InspectorError::InvalidBitIndex { .. })
        ));
        inspector.set_annotation(7..8, "sign".into()).unwrap();
        inspector
            .set_format_options(InspectorFormatOptions {
                prefix: true,
                pad_to_width: true,
                grouping: 4,
            })
            .unwrap();
        assert_eq!(inspector.format(NumericBase::Binary), "0b1000_0001");
        assert_eq!(inspector.format(NumericBase::Hexadecimal), "0x81");
        assert_eq!(inspector.format(NumericBase::Decimal), "-127");
        inspector.shift_right(1).unwrap();
        assert_eq!(inspector.value().formatted_decimal(), "-64");
        inspector.reinterpret_bits(IntegerMode::unsigned(IntegerWidth::Bits128));
        inspector.field_mask(0, 128).unwrap();
        assert_eq!(inspector.value().bit_pattern(), u128::MAX);
        assert_eq!(inspector.popcount(), 128);
        inspector
            .set_annotation(100..128, "high bits".into())
            .unwrap();
        inspector.reinterpret_bits(IntegerMode::unsigned(IntegerWidth::Bits8));
        assert!(inspector.annotation_is_valid(&inspector.annotations()[0]));
        assert!(!inspector.annotation_is_valid(&inspector.annotations()[1]));
        assert_eq!(inspector.canonical_expression(), "u8(255)");
    }
}
